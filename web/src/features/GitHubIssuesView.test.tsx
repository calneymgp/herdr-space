import {act,cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {afterEach,expect,it,vi} from 'vitest'
import {api,ApiError} from '../lib/api'
import type {GitHubIssue,GitHubRepository} from '../lib/state'
import {GitHubIssuesView} from './GitHubIssuesView'

afterEach(()=>{cleanup();vi.restoreAllMocks()})

const repositories:GitHubRepository[]=[
 {space_id:'space-a',space_name:'Space A',repository:'acme/a'},
 {space_id:'space-b',space_name:'Space B',repository:'acme/b'},
]
const issue=(number:number,title:string):GitHubIssue=>({number,title,body:'Description',state:'open',url:`https://github.com/acme/a/issues/${number}`,updated_at:'2026-10-06T10:00:00Z'})

it('ignores an old response when the repository changes during loading',async()=>{
 vi.spyOn(api,'githubStatus').mockResolvedValue({available:true,authenticated:true})
 vi.spyOn(api,'githubRepositories').mockResolvedValue({items:repositories})
 let resolveA!:(value:{items:GitHubIssue[];page:number;has_more:boolean})=>void
 const oldResponse=new Promise<{items:GitHubIssue[];page:number;has_more:boolean}>(resolve=>{resolveA=resolve})
 vi.spyOn(api,'githubIssues').mockImplementation(spaceId=>spaceId==='space-a'?oldResponse:Promise.resolve({items:[issue(2,'Issue from Space B')],page:1,has_more:false}))
 render(<GitHubIssuesView/>)
 const select=await screen.findByRole('combobox',{name:'Repository'})
 fireEvent.change(select,{target:{value:'space-b'}})
 expect(await screen.findByText('Issue from Space B')).toBeTruthy()
 await act(async()=>{resolveA({items:[issue(1,'Old issue from Space A')],page:1,has_more:false})})
 expect(screen.queryByText('Old issue from Space A')).toBeNull()
 expect(api.githubIssues).toHaveBeenCalledWith('space-b','open',1)
 const link=screen.getByRole('link',{name:'Open issue #2 on GitHub'})
 expect(link.getAttribute('href')).toBe('https://github.com/acme/a/issues/2')
 expect(link.getAttribute('rel')).toBe('noopener noreferrer')
})

it('does not apply an old issue mutation failure to a newly selected repository',async()=>{
 vi.spyOn(api,'githubStatus').mockResolvedValue({available:true,authenticated:true})
 vi.spyOn(api,'githubRepositories').mockResolvedValue({items:repositories})
 vi.spyOn(api,'githubIssues').mockImplementation(async spaceId=>({items:[spaceId==='space-a'?issue(1,'Issue A'):issue(2,'Issue B')],page:1,has_more:false}))
 let rejectOld!:(error:Error)=>void,rejectNew!:(error:Error)=>void
 const old=new Promise<{item:GitHubIssue}>((_resolve,reject)=>{rejectOld=reject})
 const next=new Promise<{item:GitHubIssue}>((_resolve,reject)=>{rejectNew=reject})
 vi.spyOn(api,'updateGithubIssue').mockReturnValueOnce(old).mockReturnValueOnce(next)
 render(<GitHubIssuesView/>)
 fireEvent.click(await screen.findByRole('button',{name:'Close issue #1'}))
 fireEvent.change(screen.getByRole('combobox',{name:'Repository'}),{target:{value:'space-b'}})
 expect(await screen.findByText('Issue B')).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Close issue #2'}))
 expect((screen.getByRole('button',{name:'Close issue #2'}) as HTMLButtonElement).disabled).toBe(true)
 await act(async()=>rejectOld(new ApiError('internal error',500)))
 expect(screen.queryByRole('alert')).toBeNull()
 expect((screen.getByRole('button',{name:'Close issue #2'}) as HTMLButtonElement).disabled).toBe(true)
 expect(screen.getByText('Issue B')).toBeTruthy()
 await act(async()=>rejectNew(new ApiError('internal error',500)))
 expect(screen.getByRole('alert').textContent).toMatch(/Could not confirm/)
})

