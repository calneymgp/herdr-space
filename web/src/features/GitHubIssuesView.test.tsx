it('rejects an overlong accented title and preserves the trimmed boundary text',async()=>{
 vi.spyOn(api,'githubStatus').mockResolvedValue({available:true,authenticated:true})
 vi.spyOn(api,'githubRepositories').mockResolvedValue({items:[repositories[0]]})
 vi.spyOn(api,'githubIssues').mockResolvedValue({items:[],page:1,has_more:false})
 const create=vi.spyOn(api,'createGithubIssue').mockResolvedValue({item:issue(4,'Issue with accents')})
 render(<GitHubIssuesView/>)
 fireEvent.click(await screen.findByRole('button',{name:'Create issue'}))
 const title=screen.getByRole('textbox',{name:'Title'})
 const body=screen.getByRole('textbox',{name:'Description'})
 const tooLongTitle='á'.repeat(129)
 const boundaryBody='a'.repeat(65536)
 fireEvent.change(title,{target:{value:tooLongTitle}})
 fireEvent.change(body,{target:{value:boundaryBody}})
 fireEvent.submit(title.closest('form')!)
 expect(create.mock.calls.length).toBe(0)
 expect(title.getAttribute('maxLength')).toBeNull()
 expect(body.getAttribute('maxLength')).toBeNull()
 expect((title as HTMLInputElement).value).toBe(tooLongTitle)
 expect((body as HTMLTextAreaElement).value).toBe(boundaryBody)
 expect(title.getAttribute('aria-invalid')).toBe('true')
 expect(body.getAttribute('aria-invalid')).toBeNull()
 expect((screen.getByRole('button',{name:'Create issue'}) as HTMLButtonElement).disabled).toBe(true)
 expect(screen.getByText(/258 \/ 256 bytes UTF-8/)).toBeTruthy()
 expect(screen.getByText(/65536 \/ 65536 bytes UTF-8/)).toBeTruthy()

 const normalizedTitle='á'.repeat(128)
 const titleWithWhitespace=`  ${normalizedTitle}  `
 fireEvent.change(title,{target:{value:titleWithWhitespace}})
 expect((title as HTMLInputElement).value).toBe(titleWithWhitespace)
 expect(title.getAttribute('aria-invalid')).toBeNull()
 expect(screen.getByText(/256 \/ 256 bytes UTF-8/)).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Create issue'}))
 await waitFor(()=>expect(create.mock.calls.length).toBe(1))
 expect(create.mock.calls[0]).toEqual(['space-a',normalizedTitle,boundaryBody])
})

