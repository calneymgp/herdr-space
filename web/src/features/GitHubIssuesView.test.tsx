it('refreshes the issue list before retrying an uncertain create and omits that warning for a definite 400',async()=>{
 vi.spyOn(api,'githubStatus').mockResolvedValue({available:true,authenticated:true})
 vi.spyOn(api,'githubRepositories').mockResolvedValue({items:[repositories[0]]})
 const list=vi.spyOn(api,'githubIssues').mockResolvedValue({items:[],page:1,has_more:false})
 const create=vi.spyOn(api,'createGithubIssue').mockRejectedValueOnce(new ApiError('internal error',503)).mockResolvedValueOnce({item:issue(8,'New issue')})
 render(<GitHubIssuesView/>)
 fireEvent.click(await screen.findByRole('button',{name:'Create issue'}))
 fireEvent.change(screen.getByRole('textbox',{name:'Title'}),{target:{value:'New issue'}})
 fireEvent.click(screen.getByRole('button',{name:'Create issue'}))
 expect((await screen.findByRole('alert')).textContent).toContain('The issue may have been created')
 const prior=list.mock.calls.length
 fireEvent.click(screen.getByRole('button',{name:'Refresh before retrying'}))
 await screen.findByRole('region',{name:'Updated issues'})
 expect(create).toHaveBeenCalledTimes(1)
 fireEvent.click(screen.getByRole('button',{name:'Create anyway'}))
 await waitFor(()=>expect(create).toHaveBeenCalledTimes(2))
 expect(list.mock.calls.length).toBeGreaterThan(prior)
 expect(list.mock.invocationCallOrder[prior]).toBeLessThan(create.mock.invocationCallOrder[1])
 cleanup();vi.restoreAllMocks()
 vi.spyOn(api,'githubStatus').mockResolvedValue({available:true,authenticated:true})
 vi.spyOn(api,'githubRepositories').mockResolvedValue({items:[repositories[0]]})
 vi.spyOn(api,'githubIssues').mockResolvedValue({items:[],page:1,has_more:false})
 vi.spyOn(api,'createGithubIssue').mockRejectedValue(new ApiError('invalid request',400))
 render(<GitHubIssuesView/>)
 fireEvent.click(await screen.findByRole('button',{name:'Create issue'}))
 fireEvent.change(screen.getByRole('textbox',{name:'Title'}),{target:{value:'New issue'}})
 fireEvent.click(screen.getByRole('button',{name:'Create issue'}))
 expect((await screen.findByRole('alert')).textContent).not.toContain('The issue may have been created')
})

